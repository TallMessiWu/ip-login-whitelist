def get_translations(lang: str) -> dict:
    """返回指定语言的翻译字典，`lang` 为 'zh'/'ru'/'en'，无法匹配时回退到中文。"""
    return TRANSLATIONS.get(lang, TRANSLATIONS["zh"])


def detect_language(accept_language: str | None) -> str:
    """
    从 Accept-Language 请求头检测用户语言：
    - 中文（zh 系列）→ 'zh'
    - 俄语（ru 系列）→ 'ru'
    - 其他语言 → 'en'
    - 无法检测 → 'zh'（默认）
    """
    if not accept_language:
        return "zh"
    raw = accept_language.lower().replace(" ", "")
    # 按优先级的逗号分隔
    tags = [t.split(";")[0].strip() for t in raw.split(",")]
    for tag in tags:
        # 提取主语言标签
        primary = tag.split("-")[0]
        if primary == "zh":
            return "zh"
        if primary == "ru":
            return "ru"
    return "en"
